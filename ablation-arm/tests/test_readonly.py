"""The read-only discipline, taken off the honour system.

`_bootstrap.py:24` says, of the upstream trees:

    `tests/test_readonly.py` checks all three by hashing the upstream trees
    around a full run, **so none of the above is on the honour system.**

`STATUS.md` recorded that this file did not exist and that the sentence was
therefore false, and deliberately left P-18's source uncorrected rather than
misrepresent what P-18 wrote.  This file is what makes the sentence true.

The claim being checked is not "the arm has no `open(..., 'w')` pointed at
upstream".  That would be a claim about the code as read.  The claim is that a
**full run** of everything this arm can do leaves the four upstream trees
byte-identical -- which covers the code as read, the code it imports, and
anything either of them calls.

The second half of the file -- "nothing moved *outside* this arm" -- was
falsified once and rebuilt.  Its criterion, its hard list and the reasons for
both live in `ablcore/outside.py`; these are its callers, plus the negative
controls that prove it still fires.  `runs/20260728T191437Z-A9-readonly-baseline/`
holds the measured evidence.

That half is checked twice over, by two mechanisms that fail for disjoint
reasons: a snapshot diff against an empty-run control (`outside.observe`), which
sees writes made by C extensions and child processes but must subtract the
concurrent fleet; and an audit hook that attributes every write to *this*
interpreter, which cannot be confused by the fleet at all but is blind to what
it cannot observe.  Neither subsumes the other, so neither was dropped.
"""

