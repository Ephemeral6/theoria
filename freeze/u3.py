def sanitize_paths(obj: Any) -> Any:
    """Strip machine-naming prefixes from every string in a verdict structure.

    tools/check_locations.py: no tracked artefact may record where its builder
    stood.  Sweep outputs land in freeze/runs/ (run scope), so they are written
    clean instead of allowlisted: the repo root (worktree or main tree) becomes
    `<repo>` and the home directory becomes `<home>`.
    """
    here = Path(__file__).resolve()
    roots: List[str] = []
    wt_root = here.parents[1]           # <root>/freeze/u3.py
    roots.append(str(wt_root))
    # a .worktrees checkout: the main tree is two levels above the checkout
    parts = wt_root.parts
    if ".worktrees" in parts:
        main_root = Path(*parts[:parts.index(".worktrees")])
        roots.append(str(main_root))
    roots.append(str(Path.home()))
    subs: List[tuple] = []
    for i, r in enumerate(sorted(set(roots), key=len, reverse=True)):
        tag = "<home>" if Path(r) == Path.home() else "<repo>"
        subs.append((r.replace("\\", "/"), tag))
        subs.append((r.replace("/", "\\"), tag))

    def walk(x: Any) -> Any:
        if isinstance(x, str):
            for frm, to in subs:
                x = x.replace(frm, to)
            return x
        if isinstance(x, list):
            return [walk(v) for v in x]
        if isinstance(x, dict):
            return {k: walk(v) for k, v in x.items()}
        return x

    return walk(obj)


# ---------------------------------------------------------------------- CLI

def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(prog="u3.py", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)

    ev = sub.add_parser("eval", help="judge one run/territory/theory directory")
    ev.add_argument("path", type=Path)
    ev.add_argument("--probe", action="store_true",
                    help="run Lean live: axiom audit + constancy probes")
    ev.add_argument("--lean", default=None, help="path to the lean binary")
    ev.add_argument("--json", action="store_true", dest="as_json")

    sw = sub.add_parser("sweep", help="judge many directories, emit a table")
    sw.add_argument("paths", nargs="+", type=Path)
    sw.add_argument("--probe", action="store_true")
    sw.add_argument("--lean", default=None)
    sw.add_argument("--md", type=Path, default=None, help="write Markdown table")
    sw.add_argument("--json", type=Path, default=None, dest="json_out",
                    help="write full verdicts as JSON")

    args = ap.parse_args(argv)
    lean_bin = args.lean or (find_lean() if args.probe else None)

    if args.cmd == "eval":
        v = evaluate(args.path, probe=args.probe, lean_bin=lean_bin)
        if args.as_json:
            print(json.dumps(v, indent=1, ensure_ascii=False, sort_keys=True))
        else:
            print("%s  %s  [%s]" % (v["verdict"].upper(), v["run"], v["label"]))
        return 0 if v["verdict"] == "attained" else 3

    rows = [evaluate(t, probe=args.probe, lean_bin=lean_bin)
            for t in expand_targets(args.paths)]
    rows = sanitize_paths(rows)
    md = to_markdown(rows)
    if args.md:
        args.md.write_text(md + "\n", encoding="utf-8")
    if args.json_out:
        args.json_out.write_text(
            json.dumps(rows, indent=1, ensure_ascii=False, sort_keys=True) + "\n",
            encoding="utf-8")
    print(md)
    return 0


if __name__ == "__main__":
    sys.exit(main())
