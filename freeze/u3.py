# -*- coding: utf-8 -*-
"""freeze/u3.py — E1, the U3 attainment evaluator (主终点一 · U3 达成率).

This is the computation code whose absence STATS_RULES.md §9.14 registers as a
launch precondition ("U3 达成率本身没有任何计算代码 … 未实现不得开跑").  It decides,
for one run directory, whether that run ATTAINED U3 under the frozen judgment.

The frozen judgment (STATS_RULES.md §1.2, verbatim anchor, 冻结时不得改)
-----------------------------------------------------------------------
A game attains U3 iff the Theoria arm produced 至少一条机器可查的定理 such that

  (a) the Lean form generated by theory-compiler COMPILES;
  (b) `#print axioms` reports only WHITELISTED axioms —
        allow  : propext, Quot.sound          (实测必需, G1 收窄记录 2026-07-29)
        never  : sorryAx                      (未完成的证明)
        never  : Lean.ofReduceBool            (native_decide bypasses the kernel)
        anything else, including Classical.choice, FAILS (b).  Classical.choice
        is additionally FLAGGED, because §1.2 preregisters a sensitivity
        listing of games that needed it ("不是禁止, 是记账");
  (c) the statement is NON-VACUOUS (§1.2.1) — not the cold-start-a3 D-A3-007
        class (`I := true`).

U3 = 证得动吗 (Theoria.md:262), NOT winning: §5.7.5 states U3 从产出物裁, does not
require the episode to finish, and does not look at `levels_completed`.  The
cheap layer's replay result is therefore REPORTED but is NOT a criterion.

Strict readings taken here (documented for the freeze territory)
----------------------------------------------------------------
1. DECLARED REFUSAL.  A run whose expensive layer says
   "not attempted: the enumerative development … too big" produced NO theorem.
   The frozen sentence requires the arm to *produce* one, so the run reads
   NOT-ATTAINED.  It is not excluded: §1.2 fixes the denominator and §1.2.1
   rules 缺格局留在分母、计为未达成 — so even on the most generous reading the
   verdict is the same; only the *label* could differ (whether it is a 缺格 g
   for §1.4's inconclusive arithmetic).  §1.2.1 defines 缺格 as "拿检查器去跑
   臂产出的那条定理跑不动" — a theorem exists but cannot be checked.  A refusal
   produced no theorem, so strictly it is NOT a 缺格; and §9.20 forbids g from
   entering adjudication arithmetic until its game-level, prior criterion
   lands.  We therefore emit verdict=not_attained, label=declared_refusal,
   flags.gap_candidate_g=true — the flag surfaces the ambiguity, changes no
   arithmetic.
2. UNDISCHARGED / UNREPORTED.  A Lean file that exists but was never run
   ("lean not on PATH"), or ran green but left no `#print axioms` evidence,
   fails strictly ((a) resp. (b) unverified is unmet, 机器可查 means checked,
   not checkable-in-principle).  `--probe` can re-run Lean to recover.
3. NON-VACUITY residual.  The executable (c) checks here are:
     * a static constant scan of `def I` / `def Goal` (catches the D-A3-007
       class with no Lean install), and
     * definitional-constancy probes under `--probe` (`fun _ => rfl` /
       `trivial`) that machine-check constancy in Lean itself.
   These catch every definitionally-constant invariant, which strictly
   includes the frozen negative control (cold-start-a3/theory/
   generated_l1_vacuous).  They do NOT decide §1.2.1's full two-witness
   predicate for a syntactically disguised constant; that residual is
   reported in `criteria.c_residuals`, never silently passed.  For
   unsolvable-kind theorems the §1.2.1 sub-checks (a)(b) are discharged by
   the co-theorems (inv_init, goal_break), (c)(d) by recorded run evidence
   (trace transitions > 0; a recorded solvable sibling / plan), each with its
   provenance named.  A theorem kind with no implemented check fails (c)
   closed, it does not pass open.

Evidence adapters (all offline, read-only; no API, no network)
--------------------------------------------------------------
  * theoria-arm run dir      : certify.json records / transfer.json .certify
  * a0-spike territory       : artifacts/a0_report.json  (+ artifacts/A0.lean)
  * cold-start-a0 territory  : artifacts/certify_lean_generated_theory_lean.json
                               (+ theory/generated/theory.lean)
  * bare theory dir          : theory.lean evaluated live (needs Lean)

CLI
---
  python u3.py eval  <dir> [--probe] [--json]
  python u3.py sweep <dir>... [--probe] [--md OUT] [--json OUT]

Exit codes: eval — 0 attained, 3 not attained, 2 error.  sweep — always 0
unless it cannot write its output (the table is the product, not the verdict).
"""

