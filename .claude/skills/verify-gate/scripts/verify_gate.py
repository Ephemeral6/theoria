def find_sh():
    """A POSIX shell that shares this repo's filesystem view. On Windows the
    `bash` on PATH is often WSL's, which cannot see C:\\Users the same way --
    prefer Git for Windows / MSYS."""
    env = os.environ.get("FLEET_SH")
    if env:
        return env
    if os.name != "nt":
        return shutil.which("sh") or shutil.which("bash") or "sh"
    candidates = []
    if os.environ.get("MSYSTEM"):
        candidates += [shutil.which("bash"), shutil.which("sh")]
    candidates += [
        r"C:\Program Files\Git\bin\bash.exe",
        r"C:\Program Files\Git\usr\bin\sh.exe",
        r"C:\Program Files (x86)\Git\bin\bash.exe",
        shutil.which("bash"),
        shutil.which("sh"),
    ]
    for c in candidates:
        if not c or not Path(c).exists():
            continue
        try:
            p = subprocess.run([c, "-c", "uname -s"], stdout=subprocess.PIPE,
                               stderr=subprocess.DEVNULL, timeout=30)
            name = p.stdout.decode("utf-8", "replace").strip().upper()
        except (OSError, subprocess.SubprocessError):
            continue
        if any(tag in name for tag in ("MINGW", "MSYS", "CYGWIN")):
            return c
    die("no MSYS/Git-Bash shell found. Install Git for Windows, or set FLEET_SH to a "
        "shell that can see this repo's paths (WSL's bash cannot).")


def cmd_run(args, root):
    ctx = load_ctx(root)
    target = args.verify or ctx.get("verify_sh")
    if not target:
        die("no verify.sh recorded. Generate one first: verify_gate.py gen")
    p = Path(target)
    if not p.is_absolute():
        p = root / p
    if not p.exists():
        die("verify.sh not found at %s" % p)
    sh = find_sh()
    posix = str(p).replace("\\", "/")
    say("running %s  (%s)" % (rel(p, root), sh))
    proc = subprocess.run([sh, posix], cwd=str(root))
    if proc.returncode == 0:
        say("")
        say("green. 收工 -> skill handoff-close")
    else:
        say("")
        say("NOT GREEN. The checklist above is the report: fix the red lines, or if one")
        say("cannot be fixed inside this ticket, carry it verbatim into RUN_STATE 的 gap")
        say("清单 and PARTNER_SYNC 的阻塞 line. 验收标准是合同,不许自降。")
    return proc.returncode


def main(argv=None):
    ap = argparse.ArgumentParser(description="Theoria fleet: verify gate")
    ap.add_argument("--now", default=None)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("gen", help="write verify.sh")
    p.add_argument("--territory", default=None)
    p.add_argument("--base", default=None)
    p.add_argument("--branch", default=None)
    p.add_argument("--prompt-id", default=None)
    p.add_argument("--run", default=None, help="run dir whose MANIFEST must reproduce")
    p.add_argument("--out", default=None, help="default <territory>/verify.sh")
    p.add_argument("--test-cmd", default=None, help="override the detected test command")
    p.add_argument("--require", action="append", help="path the工单 promised; asserts it exists")
    p.add_argument("--check", action="append", help='extra check, "name::shell command"')
    p.add_argument("--allow", action="append", help="path exempt from the boundary/sealed guards")
    p.add_argument("--pin-eol", action="store_true",
                   help="write `verify.sh text eol=lf` into the sibling .gitattributes")
    p.set_defaults(fn=cmd_gen)

    p = sub.add_parser("run", help="execute verify.sh and print the checklist")
    p.add_argument("--verify", default=None)
    p.set_defaults(fn=cmd_run)

    args = ap.parse_args(argv)
    return args.fn(args, repo_root(Path.cwd()))


if __name__ == "__main__":
    raise SystemExit(main())
