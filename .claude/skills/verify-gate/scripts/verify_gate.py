#!/usr/bin/env python
"""verify-gate -- generate and run the ticket's verify.sh.

  verify_gate.py gen  [--territory ...] [--run ...] [--check "name::cmd"] ...
  verify_gate.py run  [--verify <path>]

`gen` writes a POSIX-sh gate that runs the territory suite, the MANIFEST hash
check, and the three repo-wide guards (territory boundary, sealed pile,
credential sealing). Every check runs even after one fails, because a red run
has to show the whole checklist -- not the first stop.

`run` executes it. On Windows it finds the MSYS/Git-Bash `bash` rather than
WSL's, whose filesystem view is not this repo's.
"""

from __future__ import annotations

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _fleet import (  # noqa: E402
    detect_test_cmd, die, git, iso, load_ctx, rel, repo_root, save_ctx, say,
    utc_now, write_text,
)

HEADER = """#!/usr/bin/env sh
# verify.sh -- {prompt_id} / {branch}
# generated by .claude/skills/verify-gate at {t}; base {base}
#
# Every check runs even after one fails: a red run must print the whole
# checklist, not stop at the first red. Exit 0 only when every line is PASS.
#
#   sh verify.sh            (from anywhere -- it finds its own worktree root)
#   PYTHON=python3 sh verify.sh
set -u

ROOT=$(cd "$(dirname "$0")" && git rev-parse --show-toplevel) || exit 2
cd "$ROOT" || exit 2
PY=${{PYTHON:-python}}
export PY                       # `check` runs its command in `sh -c`, a new process
export PYTHONIOENCODING=utf-8   # this repo's prose is Chinese; consoles here are not UTF-8
PASS=0
FAIL=0
LOGDIR=$(mktemp -d 2>/dev/null || printf '%s' "${{TMPDIR:-/tmp}}/verify.$$")
mkdir -p "$LOGDIR" || exit 2

check() {{
  _name=$1
  shift
  if sh -c "$*" >"$LOGDIR/out" 2>&1; then
    printf '[PASS] %s\\n' "$_name"
    PASS=$((PASS + 1))
  else
    printf '[FAIL] %s\\n' "$_name"
    tail -n 30 "$LOGDIR/out" | sed -e 's/^/       | /'
    FAIL=$((FAIL + 1))
  fi
}}

printf '== verify.sh :: %s :: %s ==\\n' '{prompt_id}' '{branch}'
"""

FOOTER = """
printf -- '-- %s/%s green' "$PASS" "$((PASS + FAIL))"
if [ "$FAIL" -eq 0 ]; then
  printf '\\n'
  exit 0
fi
printf '  <<< NOT GREEN (%s red)\\n' "$FAIL"
exit 1
"""


def shq(s):
    return "'" + str(s).replace("'", "'\\''") + "'"


def warn_or_pin_eol(root, out, pin):
    """A shell script committed on a `core.autocrlf=true` checkout comes back
    with CRLF, and `sh` then fails on `\\r` with an error that names the wrong
    line. Pin eol=lf for it, or at least say so out loud."""
    rc, val, _ = git(["config", "--get", "core.autocrlf"], cwd=root)
    if val.strip().lower() not in ("true", "input"):
        return
    rel_out = rel(out, root)
    rc, attr, _ = git(["check-attr", "text", "eol", "--", rel_out], cwd=root)
    if "eol: lf" in attr:
        return
    ga = out.parent / ".gitattributes"
    line = "%s text eol=lf\n" % out.name
    if pin:
        prev = read_text_safe(ga)
        if line not in prev:
            write_text(ga, (prev + ("" if prev.endswith("\n") or not prev else "\n")) + line)
        say("pinned eol=lf for %s in %s" % (out.name, rel(ga, root)))
        return
    say("WARNING: core.autocrlf=%s and nothing pins eol for %s." % (val.strip(), rel_out))
    say("         Committed as-is it will come back with CRLF and `sh` will fail on \\r.")
    say("         Re-run with --pin-eol, or add `%s` to %s." % (line.strip(), rel(ga, root)))


def read_text_safe(p):
    try:
        return Path(p).read_text(encoding="utf-8")
    except OSError:
        return ""


def cmd_gen(args, root):
    ctx = load_ctx(root)
    territory = args.territory or ctx.get("territory")
    base = args.base or ctx.get("base_commit")
    branch = args.branch or ctx.get("branch") or "(no branch recorded)"
    prompt_id = args.prompt_id or ctx.get("prompt_id") or "(no prompt id)"
    if not territory:
        die("--territory is required (no ticket context; run fleet-branch-ritual first)")
    if not base:
        die("--base is required: the guards diff this branch against the commit it forked from")

    run_dir = args.run or ctx.get("run_dir")
    lines = []

    # 1 -- the territory's own suite
    test_cmd = detect_test_cmd(root / territory)
    if args.test_cmd:
        lines.append("check %s %s" % (shq("tests -- %s" % territory), shq(args.test_cmd)))
    elif test_cmd:
        lines.append("check %s %s" % (
            shq("tests -- %s" % territory),
            shq('cd %s && "$PY" -m pytest -q' % territory)))
    else:
        lines.append("printf '[ -- ] tests -- %s :: no suite in this territory (不适用)\\n'"
                     % territory)

    # 2 -- the archive still reproduces
    ra = ".claude/skills/runs-archive/scripts/runs_archive.py"
    if run_dir and (root / ra).exists():
        lines.append("check %s %s" % (
            shq("MANIFEST hashes reproduce"),
            shq('"$PY" %s check --run %s' % (ra, run_dir))))
    elif run_dir:
        lines.append("printf '[ -- ] MANIFEST :: runs-archive skill not installed\\n'")

    # 3 -- the three red lines
    g = ".claude/skills/verify-gate/scripts/guards.py"
    allow = "".join(" --allow %s" % shq(a) for a in (args.allow or []))
    lines.append("check %s %s" % (
        shq("boundary -- only %s changed" % territory),
        shq('"$PY" %s boundary --base %s --territory %s%s' % (g, base, territory, allow))))
    lines.append("check %s %s" % (
        shq("sealed pile untouched"),
        shq('"$PY" %s sealed --base %s%s' % (g, base, allow))))
    lines.append("check %s %s" % (
        shq("credential never entered a tracked file"),
        shq('"$PY" %s secret --base %s' % (g, base))))

    # 4 -- what the工单 promised
    for path in args.require or []:
        lines.append("check %s %s" % (shq("delivered: %s" % path), shq("test -e %s" % shq(path))))
    for spec in args.check or []:
        if "::" not in spec:
            die('--check expects "name::command", got %r' % spec)
        name, cmd = spec.split("::", 1)
        lines.append("check %s %s" % (shq(name.strip()), shq(cmd.strip())))

    out = Path(args.out) if args.out else (root / territory / "verify.sh")
    if not out.is_absolute():
        out = root / out
    text = HEADER.format(prompt_id=prompt_id, branch=branch, base=base[:7],
                         t=iso(utc_now(args.now))) + "\n".join(lines) + "\n" + FOOTER
    write_text(out, text)
    try:
        os.chmod(out, 0o755)
    except OSError:
        pass
    warn_or_pin_eol(root, out, args.pin_eol)
    ctx["verify_sh"] = rel(out, root)
    save_ctx(ctx, cwd=root)
    say(rel(out, root))
    say("  %d check(s). Run it:  python .claude/skills/verify-gate/scripts/verify_gate.py run"
        % (len([l for l in lines if l.startswith("check ")])))
    return 0


